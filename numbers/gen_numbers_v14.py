"""Generates numbers_v14.tex: further values of the text (test-oracle attacker, per-order medians, paired comparison with the
equal-data CosFace prototype verifier, converged MLP), computed from the result files of rapid/v2 and rapid/v2/ext/analyses."""
import json, pathlib, numpy as np
HERE = pathlib.Path(__file__).resolve().parent; ROOT = HERE.parent
V2 = ROOT / 'rapid' / 'v2'; REV = V2 / 'ext' / 'analyses'
def pct(x, d=1): return f'{100 * x:.{d}f}\\%'
V = {}
# test-oracle attacker (worst_oracle.py): RAPID against every baseline configuration of Table 8
W = json.load(open(REV / 'worst_oracle.json'))['median']; base = [k for k in W if not k.startswith('RAPID')]
V['oracle.RAPID'] = pct(W['RAPID|id']['oracle']); bo = [W[k]['oracle'] for k in base]
V['oracle.base.lo'], V['oracle.base.hi'] = pct(min(bo)), pct(max(bo))
# per-order medians with the more recent enrolment block (order "orig": enrolment block B)
R = json.load(open(V2 / 'final_results.json'))['runs']
cfg = [('RF', 'quantile'), ('RF', 'ident'), ('RF-eq', 'quantile'), ('RF-eq', 'ident'), ('MLP-eq', 'quantile'), ('MLP-eq', 'ident')]
for m in ('devchosen', 'retry20'):
    V[f'ordrecent.RAPID.{m}'] = pct(np.median([r[m] for r in R if r['system'] == 'RAPID' and r['order'] == 'orig']))
    V[f'ordrecent.base.{m}'] = pct(min(np.median([r[m] for r in R if (r['system'], r['rule']) == c and r['order'] == 'orig']) for c in cfg))
# paired per-target comparison with the equal-data CosFace prototype verifier (cfeq_stats.py)
C = json.load(open(REV / 'cfeq_stats.json'))['stats']['devchosen']
V['cfeq.dc.diff'] = f"{-100 * C['mean']:.1f}"; V['cfeq.dc.lo'] = f"{-100 * C['hi']:.1f}"; V['cfeq.dc.hi'] = f"{-100 * C['lo']:.1f}"
V['cfeq.dc.better'] = str(C['better']); V['cfeq.dc.worse'] = str(C['worse'])
# MLP trained to convergence (mlp_conv.py, early stopping up to 400 epochs)
M = [r for r in json.load(open(REV / 'mlp_conv_0_1_2_orig_swap.json')) if r['max_iter'] == 400]
for k, key in (('TAR', 'TAR'), ('devchosen', 'devchosen'), ('retry20', 'retry20')):
    V[f'mlpconv.{k}'] = pct(np.median([r[key] for r in M]))
V['mlpconv.epochs'] = f"{min(r['n_iter'] for r in M)}--{max(r['n_iter'] for r in M)}"
with open(HERE / 'numbers_v14.tex', 'w') as fh:
    fh.write('%% generated by gen_numbers_v14.py -- do not edit by hand\n\\makeatletter\n')
    for k, v in V.items(): fh.write(f'\\@namedef{{v@{k}}}{{{v}}}\n')
    fh.write('\\makeatother\n')
print(len(V), 'values written')
