"""Generates numbers.tex: every result number quoted in the prose is defined here from the result files, so the text cannot
drift from the data. Usage: python3 gen_numbers.py  (writes numbers.tex next to this script)."""
import json, os, sys, platform, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
import pathlib as _pl
_ROOT = next(p for p in [_pl.Path(__file__).resolve().parent, *_pl.Path(__file__).resolve().parents] if (p / 'paths.py').exists())
V2 = str(_ROOT / 'rapid' / 'v2'); EXT = f'{V2}/ext'; SIM = str(_ROOT / 'sim')
V = {}

def pct(x, d=1): return f'{100 * x:.{d}f}\\%'
def num(x, d=1):
    return f'{x:.{d}f}' if abs(x - round(x)) > 1e-9 else f'{int(round(x))}'

FMT = {'TAR': pct, 'acc': pct, 'pooled': lambda x: pct(x, 2), 'worst': pct, 'p99': pct, 'devchosen': pct, 'retry5': pct,
       'retry20': pct, 'multi': pct, 'EER': lambda x: pct(x, 2), 'AUC': lambda x: f'{x:.4f}', 'TAR@FAR0.01': pct,
       'TAR@FAR0.001': pct, 'eff50': num, 'ge10': num, 'ge50': num, 'eq100': num}
LOWER = {'pooled', 'worst', 'p99', 'devchosen', 'retry5', 'retry20', 'multi', 'EER', 'ge10', 'ge50', 'eq100'}

def main_numbers():
    d = json.load(open(f'{V2}/final_summary.json')); S = d['summary']
    base = ['RF|quantile', 'RF|ident', 'RF-eq|quantile', 'RF-eq|ident', 'MLP-eq|quantile', 'MLP-eq|ident']
    for m, f in FMT.items():
        V[f'RAPID.{m}'] = f(S['RAPID|ident'][m]['med'])
        vals = [S[b][m]['med'] for b in base]; V[f'best.{m}'] = f(min(vals) if m in LOWER else max(vals))
        for b in S: V[f'{b}.{m}'] = f(S[b][m]['med'])
    c = d['costs']; V['RAPID.size'] = f"{c['RAPID']['size_MB']:.1f}\\,MB"
    V['RATIO'] = f"{c['RF-eq']['size_MB'] / c['RAPID']['size_MB']:.0f}"

def env():
    import numpy, scipy, sklearn
    V['PY'] = platform.python_version(); V['NP'] = numpy.__version__; V['SP'] = scipy.__version__; V['SK'] = sklearn.__version__

def write():
    with open(f'{HERE}/numbers.tex', 'w') as fh:
        fh.write('%% generated by gen_numbers.py -- do not edit by hand\n')
        fh.write('\\makeatletter\n\\newcommand{\\V}[1]{\\@ifundefined{v@#1}{\\textbf{??#1??}\\PackageWarning{numbers}{Undefined value #1}}{\\@nameuse{v@#1}}}\n')
        for k, v in sorted(V.items()):
            fh.write(f'\\@namedef{{v@{k}}}{{{v}}}\n')
        fh.write('\\makeatother\n')
    print(len(V), 'values written')

if __name__ == '__main__':
    main_numbers()
    if os.path.exists(f'{HERE}/numbers_extra.py'):
        sys.path.insert(0, HERE); import numbers_extra; numbers_extra.add(V); numbers_extra.add2(V); numbers_extra.add3(V); numbers_extra.add4(V); numbers_extra.add5(V); numbers_extra.add6(V); numbers_extra.add7(V); numbers_extra.add8(V)
    for k in ('WORK.models', 'WORK.main', 'WORK.open', 'WORK.sweep', 'WORK.sim', 'WORK.hours'):
        V.setdefault(k, 'TBD')
    write()
